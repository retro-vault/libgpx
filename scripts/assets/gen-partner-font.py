def main():
    root = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
    blocks = {}
    for code in range(FIRST_ASCII, LAST_ASCII + 1):
        pic = GLYPHS[code]
        ink = {(x, y) for y, r in enumerate(pic)
               for x, c in enumerate(r) if c == "#"}
        moves, notes = stream([(r, 1) for r in cover(ink)])
        hits = replay(moves)
        assert set(hits) == ink, code
        assert all(v == 1 for v in hits.values()), code
        assert len(moves) < 256, code
        blocks[code] = (moves, notes)

    out = [
        "        ;; _gpx_font-unscii-8-tiny.s\n",
        "        ;;\n",
        "        ;; Unscii-8, converted at its native size to a Partner Tiny\n",
        "        ;; vector stream. The font is public domain:\n",
        "        ;; https://github.com/viznut/unscii\n",
        "        ;;\n",
        "        ;; GENERATED by scripts/assets/gen-partner-font.py --\n",
        "        ;; edit the pictures there, not the bytes here.\n",
        "        ;;\n",
        "        ;; Every pixel of every glyph is covered by exactly one\n",
        "        ;; stroke, so gpx_draw_text with BM_XOR inverts each pixel\n",
        "        ;; once instead of cancelling it. Runs are horizontal or\n",
        "        ;; vertical only, so the EF9367 rasterises them exactly.\n",
        "        ;;\n",
        "        ;; GPL2 License (see: LICENSE)\n",
        "        ;; Copyright (C) 2026 Tomaz Stih\n",
        "        ;;\n",
        "        ;; 2026-08-26   TS\n",
        "        .module gpx_font_unscii_8_tiny\n",
        "\n",
        "        .globl _gpx_font_unscii_8_tiny\n",
        "\n",
        "        .area _CODE\n",
        "_gpx_font_unscii_8_tiny::\n",
        "        ;; font header\n",
    ]
    out.append(row("        .db 4",
                   "font flags (bit0 proportional, bit1 offsets_be, bit2 vector)"))
    out.append(row(f"        .db {FIRST_ASCII}", "first ascii"))
    out.append(row(f"        .db {LAST_ASCII}", "last ascii"))
    out.append(row("        .db 0", "empty_width"))
    out.append(row("        .db 8", "max_glyph_width"))
    out.append(row("        .db 9", "glyph_height"))
    out.append(row("        .db 0", "advance"))
    out.append(row("        .db 0", "descent"))

    count = LAST_ASCII - FIRST_ASCII + 1
    offset = 8 + 2 * count
    offsets = []
    for code in range(FIRST_ASCII, LAST_ASCII + 1):
        offsets.append(offset)
        offset += 4 + len(blocks[code][0])

    out.append("\n        ;; glyph offsets\n")
    for i in range(0, count, 8):
        chunk = ", ".join(f"0x{o:04X}" for o in offsets[i:i + 8])
        out.append(f"        .dw {chunk}\n")

    out.append("\n")
    for code in range(FIRST_ASCII, LAST_ASCII + 1):
        moves, notes = blocks[code]
        label = {32: "' '", 127: "<non standard>"}.get(code, f"'{chr(code)}'")
        out.append(f"        ;; ascii {code}: {label}\n")
        out.append(row(f"        .db {GLYPH_CLASS}", "class(bits 5-7)"))
        out.append(row(f"        .db {GLYPH_W}", "width"))
        out.append(row(f"        .db {GLYPH_H}", "height"))
        out.append(row(f"        .db {len(moves)}", "# moves"))
        for mv, note in zip(moves, notes):
            out.append(row(f"        .db {mv}", f"move {note}"))

    path = os.path.join(root, "src", "partner", "_gpx_font-unscii-8-tiny.s")
    open(path, "w").write("".join(out))
    total = sum(4 + len(b[0]) for b in blocks.values()) + 8 + 2 * count
    print(f"wrote {os.path.relpath(path, root)}")
    print(f"  {count} glyphs, {sum(len(b[0]) for b in blocks.values())} moves, "
          f"{total} bytes")


if __name__ == "__main__":
    main()
